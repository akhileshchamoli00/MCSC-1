def get_tax_percentage(category_code: str, taxable_income: float) -> float:
    """
    Looks up the tax rate percentage for a given Category Code and Taxable Income.
    """
    if category_code == "A":
        brackets = BRACKETS_A
    elif category_code == "B":
        brackets = BRACKETS_B
    elif category_code == "C":
        brackets = BRACKETS_C
    else:
        return 0.0

    for min_gross, max_gross, rate in brackets:
        if min_gross <= taxable_income <= max_gross:
            return rate
    return 0.0

def calculate_employee_tax_percentage(emp_data: dict, days_worked: float = 22.0) -> float:
    """
    Calculates the tax percentage for an employee record dynamically using:
    Taxable Income = BPJS TK-JKK + BPJS TK-JKM + BPJS Kesehatan + BPJS Kes Tambahan + Additional Insurance
                     + Base Salary + Meal Allowance + Work Support + Attendance + THR + Functional + Bonus
    """
    tax_category = emp_data.get("tax_category")
    if not tax_category or tax_category not in TAX_CATEGORY_TO_CODE:
        # Fallback to the current tax_percentage if no category is provided
        return float(emp_data.get("tax_percentage") or 0.0)

    category_code = TAX_CATEGORY_TO_CODE[tax_category]

    # Calculate Meal Allowance and Work Support Allowance based on days_worked
    meal_allowance = float(days_worked * 40000.0)
    work_support = float(days_worked * 30000.0)

    # Sum up all parts of the Taxable Income formula
    bpjs_tk_jkk = float(emp_data.get("bpjs_tk_jkk") or 0.0)
    bpjs_tk_jkm = float(emp_data.get("bpjs_tk_jkm") or 0.0)
    bpjs_kesehatan = float(emp_data.get("bpjs_kesehatan") or 0.0)
    bpjs_kesehatan_tambahan = float(emp_data.get("bpjs_kesehatan_tambahan") or 0.0)
    additional_insurance = float(emp_data.get("additional_insurance") or 0.0)
    base_salary = float(emp_data.get("base_salary") or 0.0)
    attendance = float(emp_data.get("attendance_allowance") or 0.0)
    thr = float(emp_data.get("thr_allowance") or 0.0)
    functional = float(emp_data.get("functional_allowance") or 0.0)
    bonus = float(emp_data.get("bonus") or 0.0)

    taxable_income = (
        bpjs_tk_jkk + bpjs_tk_jkm + bpjs_kesehatan + bpjs_kesehatan_tambahan + additional_insurance +
        base_salary + meal_allowance + work_support + attendance + thr + functional + bonus
    )

    return get_tax_percentage(category_code, taxable_income)
